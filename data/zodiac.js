/** 由月日判断星座 */
export function zodiacOf(month, day) {
  const m = Number(month), d = Number(day);
  if (!m || !d) return null;
  return ZODIAC.find((z) => {
    const [fm, fd] = z.from, [tm, td] = z.to;
    return fm <= tm
      ? (m > fm || (m === fm && d >= fd)) && (m < tm || (m === tm && d <= td))
      : (m > fm || (m === fm && d >= fd)) || (m < tm || (m === tm && d <= td));
  }) || null;
}

